import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { countReadableWords } from "../src/lib/readingTime.js";

const postsDirectory = resolve("src/posts");
const outputPath = join(postsDirectory, "generatedMetadata.js");
const postFiles = readdirSync(postsDirectory)
    .filter((fileName) => fileName.endsWith(".mdx"))
    .sort();

const entries = postFiles.map((fileName) => {
    const source = readFileSync(join(postsDirectory, fileName), "utf8");
    const slug = fileName.slice(0, -4);

    return `    ${JSON.stringify(slug)}: ${countReadableWords(source)},`;
});

const output = [
    "// Generated by scripts/sync-post-metadata.mjs. Do not edit by hand.",
    "export const postWordCounts = {",
    ...entries,
    "};",
    "",
].join("\n");

if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== output) {
    writeFileSync(outputPath, output, "utf8");
}

console.log(`[posts] Synced ${postFiles.length} MDX word counts.`);
